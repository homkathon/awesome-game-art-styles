"""Decorate X post tables in generated README files with linkable preview images.

The source tables in resources.md files stay text-only for reuse by the web
X gallery. Preview images are separately generated by make_x_previews.py.
"""
from html import escape
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
PREVIEWS = ROOT / 'tools' / 'x_previews.json'
MEDIA = ROOT / 'tools' / 'x_media.json'
POST = re.compile(r'^\| \[(?P<title>.+?)\]\(https://x\.com/[A-Za-z0-9_]+/status/(?P<id>\d+)\) \|')


def decorate_readme(resources: str, lang: str) -> str:
    manifest = json.loads(PREVIEWS.read_text(encoding='utf-8'))
    media = json.loads(MEDIA.read_text(encoding='utf-8'))
    if set(manifest) != set(media):
        raise ValueError('X preview manifest must match media source posts')
    heading = '## Popular X posts (curated)' if lang == 'en' else '## X 热门技术帖精选'
    if resources.count(heading) != 1:
        raise ValueError('README X post section not found exactly once')
    pre, rest = resources.split(heading, 1)
    end = rest.find('\n## ')
    body, after = (rest[:end], rest[end:]) if end >= 0 else (rest, '')
    caption = ('Click a preview to open the original media in the video gallery.' if lang == 'en'
               else '点击封面可在视频画廊打开对应原帖；视频可以直接播放。')
    decorated = []
    used = set()
    for line in body.splitlines():
        m = POST.match(line)
        if m:
            post_id, title = m.group('id'), m.group('title')
            if post_id not in manifest or post_id not in media:
                raise ValueError('Missing original-source preview for X post '+post_id)
            item = manifest[post_id]
            expected = 'x-posts/previews/'+post_id+'.jpg'
            if item.get('file') != expected:
                raise ValueError('Invalid image path for X post '+post_id)
            file = ROOT / expected
            if not file.is_file() or file.stat().st_size != item['bytes']:
                raise ValueError('Missing or modified preview file for '+post_id)
            if hashlib.sha256(file.read_bytes()).hexdigest() != item['sha256']:
                raise ValueError('Corrupted preview for '+post_id)
            alt = ('Video frame' if item['kind'] == 'video-frame' else 'Original post image') if lang == 'en' else ('视频封面' if item['kind'] == 'video-frame' else '原帖图片')
            url = 'https://homkathon.github.io/awesome-game-art-styles/x-posts/#post-'+post_id
            img = (f'<a href="{url}"><img src="{expected}" width="184" '
                   f'alt="{escape(alt+": "+title, quote=True)}"></a>')
            decorated.append('| '+img+' '+line)
            used.add(post_id)
        elif line.startswith('| Post |') or line.startswith('| 帖子 |'):
            decorated.append('| Preview '+line if lang == 'en' else '| 封面 '+line)
        elif line.startswith('|:--|'):
            decorated.append('|:--'+line)
        else:
            decorated.append(line)
    if used != set(manifest):
        raise ValueError('X preview list does not match curated post tables')
    return pre + heading + '\n\n' + caption + '\n' + '\n'.join(decorated) + after
